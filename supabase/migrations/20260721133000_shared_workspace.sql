create table public.openpencil_workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'OpenPencil Workspace',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.openpencil_workspace_members (
  workspace_id uuid not null references public.openpencil_workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'editor')),
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

create table public.openpencil_documents (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.openpencil_workspaces(id) on delete cascade,
  slug text not null,
  name text not null,
  room_id text not null unique,
  snapshot_base64 text,
  snapshot_sequence bigint not null default 0,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint openpencil_documents_workspace_slug_key unique (workspace_id, slug),
  constraint openpencil_documents_slug_format
    check (slug ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
  constraint openpencil_documents_snapshot_size
    check (snapshot_base64 is null or octet_length(snapshot_base64) <= 33554432)
);

create table public.openpencil_document_updates (
  sequence bigint generated by default as identity primary key,
  document_id uuid not null references public.openpencil_documents(id) on delete cascade,
  workspace_id uuid not null references public.openpencil_workspaces(id) on delete cascade,
  client_update_id uuid not null,
  update_base64 text not null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  constraint openpencil_document_updates_document_client_key
    unique (document_id, client_update_id),
  constraint openpencil_document_updates_payload_size
    check (octet_length(update_base64) between 1 and 33554432)
);

create table public.openpencil_workspace_invites (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.openpencil_workspaces(id) on delete cascade,
  token_hash bytea not null unique,
  created_by uuid not null references auth.users(id),
  expires_at timestamptz not null,
  accepted_by uuid references auth.users(id),
  accepted_at timestamptz,
  created_at timestamptz not null default now()
);

create index openpencil_workspace_members_user_idx
  on public.openpencil_workspace_members (user_id, workspace_id);
create index openpencil_documents_workspace_idx
  on public.openpencil_documents (workspace_id);
create index openpencil_document_updates_document_sequence_idx
  on public.openpencil_document_updates (document_id, sequence);
create index openpencil_workspace_invites_workspace_idx
  on public.openpencil_workspace_invites (workspace_id, expires_at);

